create table if not exists public.ubicaciones (
  codigo text primary key,
  nombre text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists ubicaciones_nombre_lower_uidx
  on public.ubicaciones (lower(nombre));

create table if not exists public.movimientos_ubicacion (
  id bigint generated by default as identity primary key,
  folio text not null,
  codigo_material text not null references public.materiales(codigo) on delete cascade,
  ubicacion_anterior_codigo text,
  ubicacion_anterior text,
  ubicacion_nueva_codigo text not null references public.ubicaciones(codigo),
  ubicacion_nueva text not null,
  existencia jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.ubicaciones enable row level security;
alter table public.movimientos_ubicacion enable row level security;

drop policy if exists ubicaciones_staff_access on public.ubicaciones;
create policy ubicaciones_staff_access on public.ubicaciones
  for all to authenticated
  using (public.is_staff())
  with check (public.is_staff());

drop policy if exists movimientos_ubicacion_staff_access on public.movimientos_ubicacion;
create policy movimientos_ubicacion_staff_access on public.movimientos_ubicacion
  for all to authenticated
  using (public.is_staff())
  with check (public.is_staff());

grant select, insert, update on public.ubicaciones to authenticated;
grant select, insert on public.movimientos_ubicacion to authenticated;
grant usage, select on sequence public.movimientos_ubicacion_id_seq to authenticated;

create or replace function public.asignar_inventario_ubicacion(
  p_ubicacion_codigo text,
  p_folio text,
  p_items jsonb
)
returns integer
language plpgsql
set search_path = public
as $$
declare
  v_ubicacion public.ubicaciones%rowtype;
  v_item jsonb;
  v_material public.materiales%rowtype;
  v_anterior_codigo text;
  v_anterior text;
  v_codigo text;
  v_procesados integer := 0;
begin
  if not public.is_staff() then
    raise exception 'NO_AUTORIZADO';
  end if;
  if coalesce(trim(p_folio), '') = '' or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'DATOS_DE_ASIGNACION_INVALIDOS';
  end if;

  select * into v_ubicacion
  from public.ubicaciones
  where codigo = p_ubicacion_codigo;
  if not found then
    raise exception 'UBICACION_NO_ENCONTRADA';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_codigo := nullif(trim(v_item->>'codigo'), '');
    if v_codigo is null then
      raise exception 'CODIGO_MATERIAL_INVALIDO';
    end if;

    select * into v_material
    from public.materiales
    where codigo = v_codigo
    for update;
    if not found then
      raise exception 'MATERIAL_NO_ENCONTRADO: %', v_codigo;
    end if;

    v_anterior_codigo := nullif(v_material.data->>'ubicacionCodigo', '');
    v_anterior := nullif(v_material.data->>'ubicacion', '');

    update public.materiales
    set data = jsonb_set(
      jsonb_set(coalesce(v_material.data, '{}'::jsonb), '{ubicacion}', to_jsonb(v_ubicacion.nombre), true),
      '{ubicacionCodigo}', to_jsonb(v_ubicacion.codigo), true
    )
    where codigo = v_codigo;

    insert into public.movimientos_ubicacion (
      folio, codigo_material, ubicacion_anterior_codigo, ubicacion_anterior,
      ubicacion_nueva_codigo, ubicacion_nueva, existencia
    )
    values (
      p_folio, v_codigo, v_anterior_codigo, v_anterior,
      v_ubicacion.codigo, v_ubicacion.nombre,
      coalesce(v_item->'existencia', '{}'::jsonb)
    );

    v_procesados := v_procesados + 1;
  end loop;

  return v_procesados;
end;
$$;

grant execute on function public.asignar_inventario_ubicacion(text, text, jsonb) to authenticated;
