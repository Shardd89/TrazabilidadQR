-- ============================================================================
-- ENTRADAS DE MATERIAL (FASE 1)
-- ============================================================================
-- Objetivo:
--   * Un material (código) puede tener varias recepciones/lotes.
--   * Cada recepción guarda su propia cantidad y datos de trazabilidad
--     (manufactura, longitud IND, heat, lote MP, certificado, orden, PO,
--     ubicación y fecha de recibo).
--   * La existencia del código es la suma de sus entradas menos surtidos y
--     ajustes.
--
-- Este script es idempotente: se puede ejecutar varias veces.
--
-- BASE EXISTENTE (caso normal): ejecutar solamente
--   1) supabase_almacenes.sql          (idempotente; ya incluye ubicaciones)
--   2) supabase_entradas_material.sql  (este script, al final)
-- No vuelva a ejecutar supabase_ubicaciones.sql: es solo para una instalación
-- nueva y se niega a correr cuando public.almacenes ya existe.
-- Tampoco ejecute supabase_existencias_vista.sql ni supabase_surtido_atomico.sql
-- después de este script: revertirían la vista y las funciones por lote.
--
-- INSTALACIÓN NUEVA: supabase_ubicaciones.sql, luego supabase_almacenes.sql,
-- opcionalmente supabase_existencias_vista.sql y al final este script.
-- ============================================================================

begin;

-- ----------------------------------------------------------------------------
-- PASO 0: Función de conversión de longitud (idempotente)
-- ----------------------------------------------------------------------------
create or replace function public.factor_longitud(p_unidad text)
returns numeric
language sql
immutable
as $$
  select case lower(coalesce(p_unidad, ''))
    when 'cm' then 10
    when 'm' then 1000
    when 'in' then 25.4
    else 1
  end;
$$;

revoke all on function public.factor_longitud(text) from public, anon;
grant execute on function public.factor_longitud(text) to authenticated;

-- ----------------------------------------------------------------------------
-- PASO 1: Tabla de entradas
-- ----------------------------------------------------------------------------
create table if not exists public.entradas_material (
  id bigint generated by default as identity primary key,
  codigo_material text not null references public.materiales(codigo)
    on update cascade on delete cascade,
  cantidad numeric not null check (cantidad > 0),
  longitud_individual numeric,
  longitud numeric,
  longitud_unidad text,
  peso numeric,
  peso_unidad text,
  ubicacion_codigo text,
  ubicacion_nombre text,
  almacen_codigo text,
  fecha_recibo date,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  created_by text
);

create index if not exists entradas_material_codigo_idx
  on public.entradas_material (codigo_material);
create index if not exists entradas_material_ubicacion_idx
  on public.entradas_material (ubicacion_codigo);
create index if not exists entradas_material_fecha_idx
  on public.entradas_material (fecha_recibo desc);
create index if not exists entradas_material_heat_idx
  on public.entradas_material ((data->>'numeroHeat'));
create index if not exists entradas_material_lote_idx
  on public.entradas_material ((data->>'numeroLoteMP'));
create index if not exists entradas_material_cert_idx
  on public.entradas_material ((data->>'numeroCertificado'));

comment on table public.entradas_material is
  'Recepciones/lotes de un material. Cada fila conserva la trazabilidad de esa entrada.';

-- ----------------------------------------------------------------------------
-- PASO 2: Enlazar despachos y ajustes con la entrada
-- ----------------------------------------------------------------------------
alter table public.despachos
  add column if not exists entrada_id bigint references public.entradas_material(id)
    on update cascade on delete set null;

alter table public.despachos
  drop constraint if exists despachos_codigo_t_key;

-- La clave única anterior (codigo, t) se conserva como índice único para no
-- romper la restauración. t sigue siendo único por renglón de salida.
create unique index if not exists despachos_codigo_t_uidx
  on public.despachos (codigo, t);

create index if not exists despachos_entrada_idx
  on public.despachos (entrada_id);

do $$
begin
  if to_regclass('public.ajustes_inventario_ciclico') is not null then
    execute 'alter table public.ajustes_inventario_ciclico
      add column if not exists entrada_id bigint references public.entradas_material(id)
        on update cascade on delete set null';
    execute 'create index if not exists ajustes_inventario_entrada_idx
      on public.ajustes_inventario_ciclico (entrada_id)';
  end if;
end;
$$;

-- ----------------------------------------------------------------------------
-- PASO 3: Respaldo: una entrada por cada material existente
-- ----------------------------------------------------------------------------
-- Solo se crea si el material todavía no tiene entradas. Los materiales con
-- cantidad 0 no generan entrada (su existencia inicial es cero).
insert into public.entradas_material (
  codigo_material, cantidad, longitud_individual, longitud, longitud_unidad,
  peso, peso_unidad, ubicacion_codigo, ubicacion_nombre, almacen_codigo,
  fecha_recibo, data, created_by
)
select
  m.codigo,
  coalesce(nullif(m.data->>'cantidad', '')::numeric, 0),
  nullif(m.data->>'longitudIndividual', '')::numeric,
  nullif(m.data->>'longitud', '')::numeric,
  coalesce(nullif(m.data->>'longU', ''), nullif(m.data->>'longitudUnidad', ''), 'mm'),
  nullif(m.data->>'peso', '')::numeric,
  nullif(coalesce(nullif(m.data->>'pesoU', ''), nullif(m.data->>'pesoUnidad', '')), ''),
  nullif(m.data->>'ubicacionCodigo', ''),
  nullif(m.data->>'ubicacion', ''),
  nullif(m.data->>'ubicacionAlmacenCodigo', ''),
  case
    when (m.data->>'fechaRecibo') ~ '^\d{4}-\d{2}-\d{2}$'
    then (m.data->>'fechaRecibo')::date
    else null
  end,
  m.data,
  'Migración de entradas'
from public.materiales m
where coalesce(nullif(m.data->>'cantidad', '')::numeric, 0) > 0
  and not exists (
    select 1 from public.entradas_material e
    where e.codigo_material = m.codigo
  );

-- Enlazar despachos históricos cuando el material tiene una sola entrada.
update public.despachos d
set entrada_id = e.id
from public.entradas_material e
where d.entrada_id is null
  and e.codigo_material = d.codigo
  and (
    select count(*) from public.entradas_material e2
    where e2.codigo_material = d.codigo
  ) = 1;

-- Enlazar ajustes históricos cuando el material tiene una sola entrada.
do $$
begin
  if to_regclass('public.ajustes_inventario_ciclico') is not null then
    execute $sql$
      update public.ajustes_inventario_ciclico a
      set entrada_id = e.id
      from public.entradas_material e
      where a.entrada_id is null
        and e.codigo_material = a.codigo_material
        and (
          select count(*) from public.entradas_material e2
          where e2.codigo_material = a.codigo_material
        ) = 1
    $sql$;
  end if;
end;
$$;

-- Mantener data.cantidad como suma de piezas de las entradas, por
-- compatibilidad con etiquetas y respaldos anteriores.
update public.materiales m
set data = jsonb_set(
  m.data,
  '{cantidad}',
  to_jsonb(x.piezas),
  true
)
from (
  select codigo_material, sum(cantidad) as piezas
  from public.entradas_material
  group by codigo_material
) x
where x.codigo_material = m.codigo;

-- ----------------------------------------------------------------------------
-- PASO 4: Vista de existencias por entrada
-- ----------------------------------------------------------------------------
create or replace view public.existencias_entradas as
with mat as (
  select
    m.codigo,
    (
      lower(coalesce(m.data->>'tipoRegistro', '')) in ('mp', 'materia prima')
      or lower(coalesce(m.data->>'esMP', 'false')) = 'true'
    ) as es_mp
  from public.materiales m
),
base as (
  select
    e.*,
    mat.es_mp,
    case
      when mat.es_mp and coalesce(e.longitud_individual, 0) > 0 then 'longitud'
      when mat.es_mp and coalesce(e.longitud, 0) > 0 then 'longitud'
      else 'piezas'
    end as modo,
    case
      when mat.es_mp and coalesce(e.longitud_individual, 0) > 0 then 'mm'
      when mat.es_mp and coalesce(e.longitud, 0) > 0
        then case
          when coalesce(e.longitud_unidad, '') in ('mm', 'cm', 'm', 'in')
          then e.longitud_unidad
          else 'mm'
        end
      else 'PZ'
    end as unidad,
    case
      when mat.es_mp and coalesce(e.longitud_individual, 0) > 0 then e.longitud_individual
      when mat.es_mp and coalesce(e.longitud, 0) > 0 then e.longitud
      else null
    end as longitud_base,
    case
      when mat.es_mp and coalesce(e.longitud_individual, 0) > 0
        then e.cantidad * e.longitud_individual
      when mat.es_mp and coalesce(e.longitud, 0) > 0
        then e.cantidad * e.longitud
      else e.cantidad
    end as total
  from public.entradas_material e
  join mat on mat.codigo = e.codigo_material
),
surtido as (
  select
    b.id,
    sum(coalesce(nullif(d.data->>'cantidad', '')::numeric, 0)) as piezas,
    sum(
      coalesce(nullif(d.data->>'longitud', '')::numeric, 0)
      * public.factor_longitud(
          case
            when coalesce(d.data->>'unidad', '') in ('mm', 'cm', 'm', 'in')
            then d.data->>'unidad'
            else b.unidad
          end
        )
      / public.factor_longitud(b.unidad)
    ) as base
  from base b
  join public.despachos d on d.entrada_id = b.id
  group by b.id
),
ajustes as (
  select
    b.id,
    sum(case when a.unidad = 'PZ' then a.diferencia else 0 end) as piezas,
    sum(
      case
        when a.unidad in ('mm', 'cm', 'm', 'in')
        then a.diferencia * public.factor_longitud(a.unidad) / public.factor_longitud(b.unidad)
        else 0
      end
    ) as base
  from base b
  join public.ajustes_inventario_ciclico a on a.entrada_id = b.id
  group by b.id
)
select
  b.id,
  b.codigo_material,
  b.cantidad,
  b.longitud_individual,
  b.longitud,
  b.longitud_unidad,
  b.peso,
  b.peso_unidad,
  b.ubicacion_codigo,
  b.ubicacion_nombre,
  b.almacen_codigo,
  b.fecha_recibo,
  b.created_at,
  b.modo,
  b.unidad,
  b.longitud_base,
  round(b.total, 4) as total,
  round(
    case when b.modo = 'longitud' then coalesce(s.base, 0) else coalesce(s.piezas, 0) end,
    4
  ) as surtido,
  round(
    case when b.modo = 'longitud' then coalesce(a.base, 0) else coalesce(a.piezas, 0) end,
    4
  ) as ajustes,
  round(
    b.total
    - case when b.modo = 'longitud' then coalesce(s.base, 0) else coalesce(s.piezas, 0) end
    + case when b.modo = 'longitud' then coalesce(a.base, 0) else coalesce(a.piezas, 0) end,
    4
  ) as existencia
from base b
left join surtido s on s.id = b.id
left join ajustes a on a.id = b.id;

comment on view public.existencias_entradas is
  'Existencia por entrada/lote. Unidad: PZ o unidad base de longitud.';

revoke all on public.existencias_entradas from public, anon, authenticated;

-- ----------------------------------------------------------------------------
-- PASO 5: Vista de existencias por material (agrega entradas)
-- ----------------------------------------------------------------------------
create or replace view public.existencias_materiales as
with mat as (
  select
    m.codigo,
    (
      lower(coalesce(m.data->>'tipoRegistro', '')) in ('mp', 'materia prima')
      or lower(coalesce(m.data->>'esMP', 'false')) = 'true'
    ) as es_mp,
    coalesce(nullif(m.data->>'longitudIndividual', '')::numeric, 0) as li_material,
    coalesce(nullif(m.data->>'longitud', '')::numeric, 0) as l_material,
    case
      when coalesce(nullif(m.data->>'longU', ''), nullif(m.data->>'longitudUnidad', ''), 'mm')
           in ('mm', 'cm', 'm', 'in')
      then coalesce(nullif(m.data->>'longU', ''), nullif(m.data->>'longitudUnidad', ''), 'mm')
      else 'mm'
    end as u_material
  from public.materiales m
),
ent as (
  select
    e.codigo_material as codigo,
    count(*)::integer as entradas,
    sum(e.cantidad) as piezas,
    sum(
      e.cantidad * case
        when coalesce(e.longitud_individual, 0) > 0 then e.longitud_individual
        when coalesce(e.longitud, 0) > 0
          then e.longitud * public.factor_longitud(coalesce(nullif(e.longitud_unidad, ''), 'mm'))
        else 0
      end
    ) as longitud_mm,
    bool_or(
      coalesce(e.longitud_individual, 0) > 0
      or coalesce(e.longitud, 0) > 0
    ) as tiene_longitud,
    min(
      case
        when coalesce(e.longitud_individual, 0) > 0 then e.longitud_individual
        when coalesce(e.longitud, 0) > 0
          then e.longitud * public.factor_longitud(coalesce(nullif(e.longitud_unidad, ''), 'mm'))
        else null
      end
    ) as min_longitud,
    max(
      case
        when coalesce(e.longitud_individual, 0) > 0 then e.longitud_individual
        when coalesce(e.longitud, 0) > 0
          then e.longitud * public.factor_longitud(coalesce(nullif(e.longitud_unidad, ''), 'mm'))
        else null
      end
    ) as max_longitud
  from public.entradas_material e
  group by e.codigo_material
),
calc as (
  select
    m.codigo,
    m.es_mp,
    coalesce(e.entradas, 0) as entradas,
    coalesce(e.piezas, 0) as cantidad_inicial,
    case
      when m.es_mp and coalesce(e.tiene_longitud, false) then 'longitud'
      else 'piezas'
    end as modo,
    case
      when m.es_mp and coalesce(e.tiene_longitud, false) then 'mm'
      else 'PZ'
    end as unidad,
    case
      when m.es_mp and coalesce(e.tiene_longitud, false) then
        case
          when e.min_longitud is not null and e.min_longitud = e.max_longitud
          then e.min_longitud
          else null
        end
      else null
    end as longitud_base,
    case
      when m.es_mp and coalesce(e.tiene_longitud, false)
        then coalesce(e.longitud_mm, 0)
      else coalesce(e.piezas, 0)
    end as total,
    (
      coalesce(e.entradas, 0) > 1
      and e.min_longitud is not null
      and e.max_longitud is not null
      and e.min_longitud <> e.max_longitud
    ) as longitudes_mezcladas
  from mat m
  left join ent e on e.codigo = m.codigo
),
surtido as (
  select
    c.codigo,
    sum(coalesce(nullif(d.data->>'cantidad', '')::numeric, 0)) as piezas,
    sum(
      coalesce(nullif(d.data->>'longitud', '')::numeric, 0)
      * public.factor_longitud(
          case
            when coalesce(d.data->>'unidad', '') in ('mm', 'cm', 'm', 'in')
            then d.data->>'unidad'
            else c.unidad
          end
        )
      / public.factor_longitud(c.unidad)
    ) as base
  from calc c
  join public.despachos d on d.codigo = c.codigo
  group by c.codigo, c.unidad
),
ajustes as (
  select
    c.codigo,
    sum(case when a.unidad = 'PZ' then a.diferencia else 0 end) as piezas,
    sum(
      case
        when a.unidad in ('mm', 'cm', 'm', 'in')
        then a.diferencia * public.factor_longitud(a.unidad) / public.factor_longitud(c.unidad)
        else 0
      end
    ) as base
  from calc c
  join public.ajustes_inventario_ciclico a on a.codigo_material = c.codigo
  group by c.codigo, c.unidad
)
select
  c.codigo,
  c.modo,
  c.unidad,
  c.cantidad_inicial,
  c.longitud_base,
  round(c.total, 4) as total,
  round(
    case when c.modo = 'longitud' then coalesce(s.base, 0) else coalesce(s.piezas, 0) end,
    4
  ) as surtido,
  round(
    case when c.modo = 'longitud' then coalesce(a.base, 0) else coalesce(a.piezas, 0) end,
    4
  ) as ajustes,
  round(
    c.total
    - case when c.modo = 'longitud' then coalesce(s.base, 0) else coalesce(s.piezas, 0) end
    + case when c.modo = 'longitud' then coalesce(a.base, 0) else coalesce(a.piezas, 0) end,
    4
  ) as existencia,
  c.entradas,
  c.longitudes_mezcladas
from calc c
left join surtido s on s.codigo = c.codigo
left join ajustes a on a.codigo = c.codigo;

comment on view public.existencias_materiales is
  'Existencias por código, sumando todas sus entradas. Siempre actualizada.';

revoke all on public.existencias_materiales from public, anon, authenticated;

-- ----------------------------------------------------------------------------
-- PASO 6: RPC de consulta de existencias (mismo contrato + entradas)
-- ----------------------------------------------------------------------------
drop function if exists public.obtener_existencias_materiales(text[]);

create function public.obtener_existencias_materiales(
  p_codigos text[] default null
)
returns table (
  codigo text,
  modo text,
  unidad text,
  cantidad_inicial numeric,
  longitud_base numeric,
  total numeric,
  surtido numeric,
  ajustes numeric,
  existencia numeric,
  entradas integer,
  longitudes_mezcladas boolean
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if not (public.is_staff() or public.is_admin()) then
    raise exception 'NO_AUTORIZADO';
  end if;

  return query
  select
    e.codigo,
    e.modo,
    e.unidad,
    e.cantidad_inicial,
    e.longitud_base,
    e.total,
    e.surtido,
    e.ajustes,
    e.existencia,
    e.entradas,
    e.longitudes_mezcladas
  from public.existencias_materiales e
  where p_codigos is null or e.codigo = any (p_codigos)
  order by e.codigo;
end;
$$;

revoke all on function public.obtener_existencias_materiales(text[]) from public, anon;
grant execute on function public.obtener_existencias_materiales(text[]) to authenticated;

comment on function public.obtener_existencias_materiales(text[]) is
  'Consulta de existencias por código para staff/admin. Incluye número de entradas y si mezcla longitudes.';

-- ----------------------------------------------------------------------------
-- PASO 7: RPC para registrar una o varias entradas de forma atómica
-- ----------------------------------------------------------------------------
create or replace function public.registrar_entradas(
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_item jsonb;
  v_entrada jsonb;
  v_material jsonb;
  v_codigo text;
  v_cantidad numeric;
  v_id bigint;
  v_resultados jsonb := '[]'::jsonb;
  v_registradas integer := 0;
  v_total numeric;
begin
  if not public.is_admin() then
    raise exception 'NO_AUTORIZADO';
  end if;

  if jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) = 0
    or jsonb_array_length(p_items) > 50 then
    raise exception 'DATOS_DE_ENTRADA_INVALIDOS';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_codigo := nullif(trim(v_item->>'codigo'), '');
    v_entrada := v_item->'entrada';
    v_material := coalesce(v_item->'material', '{}'::jsonb);

    if v_codigo is null or v_entrada is null or jsonb_typeof(v_entrada) <> 'object' then
      raise exception 'DATOS_DE_ENTRADA_INVALIDOS';
    end if;

    v_cantidad := coalesce(nullif(v_entrada->>'cantidad', '')::numeric, 0);
    if v_cantidad <= 0 then
      raise exception 'CANTIDAD_DE_ENTRADA_INVALIDA: %', v_codigo;
    end if;

    -- Crear el material si no existe. Si ya existe, conservar sus datos base.
    insert into public.materiales (codigo, data)
    values (
      v_codigo,
      v_material || jsonb_build_object('cantidad', v_cantidad)
    )
    on conflict (codigo) do nothing;

    perform 1 from public.materiales where codigo = v_codigo for update;

    insert into public.entradas_material (
      codigo_material,
      cantidad,
      longitud_individual,
      longitud,
      longitud_unidad,
      peso,
      peso_unidad,
      ubicacion_codigo,
      ubicacion_nombre,
      almacen_codigo,
      fecha_recibo,
      data,
      created_by
    )
    values (
      v_codigo,
      v_cantidad,
      nullif(v_entrada->>'longitudIndividual', '')::numeric,
      nullif(v_entrada->>'longitud', '')::numeric,
      nullif(v_entrada->>'longitudUnidad', ''),
      nullif(v_entrada->>'peso', '')::numeric,
      nullif(v_entrada->>'pesoUnidad', ''),
      nullif(v_entrada->>'ubicacionCodigo', ''),
      nullif(v_entrada->>'ubicacion', ''),
      nullif(v_entrada->>'almacenCodigo', ''),
      case
        when (v_entrada->>'fechaRecibo') ~ '^\d{4}-\d{2}-\d{2}$'
        then (v_entrada->>'fechaRecibo')::date
        else null
      end,
      coalesce(v_entrada->'data', '{}'::jsonb)
        || jsonb_build_object(
          'codigo', v_codigo,
          'cantidad', v_cantidad,
          'ubicacion', v_entrada->>'ubicacion',
          'ubicacionCodigo', v_entrada->>'ubicacionCodigo',
          'ubicacionAlmacenCodigo', v_entrada->>'almacenCodigo',
          'fechaRecibo', v_entrada->>'fechaRecibo'
        ),
      coalesce(nullif(auth.jwt()->>'email', ''), 'Administrador')
    )
    returning id into v_id;

    select coalesce(sum(cantidad), 0)
    into v_total
    from public.entradas_material
    where codigo_material = v_codigo;

    update public.materiales
    set data = jsonb_set(data, '{cantidad}', to_jsonb(v_total), true)
    where codigo = v_codigo;

    v_resultados := v_resultados || jsonb_build_array(
      jsonb_build_object(
        'id', v_id,
        'codigo', v_codigo,
        'cantidad', v_cantidad,
        'total', v_total
      )
    );
    v_registradas := v_registradas + 1;
  end loop;

  return jsonb_build_object(
    'registradas', v_registradas,
    'entradas', v_resultados
  );
end;
$$;

revoke all on function public.registrar_entradas(jsonb) from public, anon;
grant execute on function public.registrar_entradas(jsonb) to authenticated;

comment on function public.registrar_entradas(jsonb) is
  'Registra hasta 50 entradas/recepciones de forma atómica. Si el código no existe lo crea; si existe, acumula sin sobrescribir sus datos base.';

-- ----------------------------------------------------------------------------
-- PASO 8: RPC de consulta de entradas (staff/admin)
-- ----------------------------------------------------------------------------
create or replace function public.obtener_entradas_material(p_codigo text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_entradas jsonb;
begin
