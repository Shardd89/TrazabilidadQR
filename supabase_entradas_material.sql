    raise exception 'NO_AUTORIZADO';
  end if;

  select coalesce(jsonb_agg(to_jsonb(e) order by e.created_at, e.id), '[]'::jsonb)
  into v_entradas
  from public.entradas_material e
  where e.codigo_material = p_codigo;

  return v_entradas;
end;
$$;

